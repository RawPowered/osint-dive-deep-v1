def discover_tools() -> list[DiscoveredTool]:
    discovered: list[DiscoveredTool] = []
    for spec in TOOL_SPECS:
        executable = next((shutil.which(name) for name in spec.executables if shutil.which(name)), None)
        discovered.append(DiscoveredTool(spec=spec, executable=executable))
    return discovered


def registry_by_key() -> dict[str, ToolSpec]:
    return {spec.key: spec for spec in TOOL_SPECS}
