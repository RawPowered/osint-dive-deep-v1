'use strict';
const assert = require('assert/strict');
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'public/admin/divedeep.html'), 'utf8');
const js = fs.readFileSync(path.join(root, 'public/js/divedeep-admin-v1.13.0.js'), 'utf8');
const routes = fs.readFileSync(path.join(root, 'src/routes/adminDiveDeep.js'), 'utf8');
const integrations = fs.readFileSync(path.join(root, 'src/services/diveDeepIntegrations.js'), 'utf8');
assert.match(html, /Retention &amp; Artifacts/);
assert.match(html, /runRetentionSweep/);
assert.match(html, /retentionMetrics/);
assert.match(html, /divedeep-admin-v1\.13\.0\.js/);
for (const token of ['Verify storage access','Lifecycle template','sha256_header','sse_kms','openArtifact','changeArtifactHold','extendArtifact','runRetentionSweep']) assert.match(js, new RegExp(token));
for (const route of ['artifacts/upload-authorizations','artifacts/:artifactId/finalize','artifacts/:artifactId/access','artifacts/:artifactId/disposition','retention/run','storage/lifecycle-template','object_storage/verify-access']) assert.match(routes, new RegExp(route.replaceAll('/', '\\/')));
assert.match(integrations, /maximumArtifactBytes/);
assert.match(integrations, /objectTaggingEnabled/);
assert.match(integrations, /lifecycleSafetyNetEnabled/);
assert.doesNotMatch(js, /localStorage|sessionStorage/);
const ids = [...html.matchAll(/\sid="([^"]+)"/g)].map((match) => match[1]);
assert.deepEqual([...new Set(ids.filter((id, index) => ids.indexOf(id) !== index))], []);
console.log('DiveDeep Phase 3 admin UI and route contract checks passed');
