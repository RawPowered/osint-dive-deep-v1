'use strict';
const assert = require('assert/strict');
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'public/admin/divedeep.html'), 'utf8');
const js = fs.readFileSync(path.join(root, 'public/js/divedeep-admin-v1.13.0.js'), 'utf8');
assert.match(html, /divedeep-admin-v1\.13\.0\.js/);
for (const id of ['workerRuntimeMetrics', 'workerInstanceGrid', 'runWorkerLeaseSweep']) assert.match(html, new RegExp(`id="${id}"`));
assert.match(html, /one-time token/i);
assert.match(html, /leases one job/i);
assert.match(js, /\/api\/divedeep\/workers/);
assert.match(js, /lease-sweep/);
assert.match(js, /Active workers/);
assert.match(js, /Cleanup/);
assert.match(html, /name="workerVersion"/);
assert.match(html, /name="workerProtocolVersion"/);
assert.match(js, /workerProtocolVersion/);
console.log('DiveDeep Phase 4 admin UI checks passed');
