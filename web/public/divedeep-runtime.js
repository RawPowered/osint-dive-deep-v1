/*
 * DiveDeep customer-site runtime configuration.
 *
 * The installer generates a replacement of this file with the API origin for
 * a split deployment. It contains no credentials, keys, or customer data.
 */
(() => {
  const configured = String(window.DiveDeepRuntime?.apiOrigin || '').trim().replace(/\/+$/, '');
  const apiUrl = (path) => {
    if (!String(path).startsWith('/')) throw new Error('DiveDeep API paths must begin with /');
    if (!configured) {
      throw new Error('DiveDeep frontend is not configured. Upload the divedeep-runtime.js generated by the API installer.');
    }
    return `${configured}${path}`;
  };
  window.DiveDeepRuntime = Object.freeze({ apiOrigin: configured, configured: Boolean(configured) });
  window.DiveDeepClient = Object.freeze({ apiOrigin: configured, configured: Boolean(configured), apiUrl });
})();
