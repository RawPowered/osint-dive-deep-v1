const CONNECTION_PROOF_TTL_MS = 10 * 60 * 1000;

function requestOrigin(req) {
  const protocol = req.protocol || (req.secure ? 'https' : 'http');
  return `${protocol}://${req.get('host')}`;
}

function preparePrivateStorageDir(input) {
  const fallback = path.join(ROOT, 'storage', 'divedeep-private');
  const requested = String(input || fallback).trim();
  if (!path.isAbsolute(requested)) throw new Error('Private file directory must be an absolute server path');
  const resolved = path.resolve(requested);
  const publicRoot = `${path.resolve(ROOT, 'public')}${path.sep}`;
  if (resolved === path.resolve(ROOT, 'public') || resolved.startsWith(publicRoot)) {
    throw new Error('Private file directory cannot be inside the public web root');
  }
  fs.mkdirSync(resolved, { recursive: true, mode: 0o700 });
  try { fs.chmodSync(resolved, 0o700); } catch { /* hosting platform may control modes */ }
  return resolved;
}

function frontendRuntimeConfig(apiOrigin) {
  return `/* Generated by the DiveDeep installer. No secrets are stored here. */\n(() => {\n  const apiOrigin = ${JSON.stringify(apiOrigin)};\n  const apiUrl = (path) => {\n    if (!String(path).startsWith('/')) throw new Error('DiveDeep API paths must begin with /');\n    return apiOrigin + path;\n  };\n  window.DiveDeepRuntime = Object.freeze({ apiOrigin, configured: true });\n  window.DiveDeepClient = Object.freeze({ apiOrigin, configured: true, apiUrl });\n})();\n`;
}

function canonicalDatabaseInput(input = {}) {
  return {
    host: String(input.host || '127.0.0.1').trim(),
    port: Number(input.port || 3306),
    user: String(input.user || '').trim(),
    password: String(input.password || ''),
    database: String(input.database || '').trim(),
    createDatabase: Boolean(input.createDatabase),
  };
}

function databaseFingerprint(input, proofKey) {
  return crypto.createHmac('sha256', proofKey)
    .update(JSON.stringify(canonicalDatabaseInput(input)))
    .digest('base64url');
}

function createConnectionProof(input, proofKey, now = Date.now()) {
  const payload = Buffer.from(JSON.stringify({
    expiresAt: now + CONNECTION_PROOF_TTL_MS,
    nonce: crypto.randomBytes(16).toString('base64url'),
    fingerprint: databaseFingerprint(input, proofKey),
  })).toString('base64url');
  const signature = crypto.createHmac('sha256', proofKey).update(payload).digest('base64url');
  return `${payload}.${signature}`;
}

function verifyConnectionProof(token, input, proofKey, now = Date.now()) {
  const [payload, suppliedSignature, extra] = String(token || '').split('.');
  if (!payload || !suppliedSignature || extra) return false;
  const expectedSignature = crypto.createHmac('sha256', proofKey).update(payload).digest('base64url');
  const supplied = Buffer.from(suppliedSignature);
  const expected = Buffer.from(expectedSignature);
  if (supplied.length !== expected.length || !crypto.timingSafeEqual(supplied, expected)) return false;
  try {
    const parsed = JSON.parse(Buffer.from(payload, 'base64url').toString('utf8'));
    const expectedFingerprint = databaseFingerprint(input, proofKey);
    const actualFingerprint = String(parsed.fingerprint || '');
    const actual = Buffer.from(actualFingerprint);
    const fingerprint = Buffer.from(expectedFingerprint);
    return Number(parsed.expiresAt) >= now && actual.length === fingerprint.length &&
      crypto.timingSafeEqual(actual, fingerprint);
  } catch {
    return false;
  }
}

function deriveBootstrapAdmin(seed) {
  if (!Buffer.isBuffer(seed) || seed.length < 32) throw new Error('Bootstrap seed must contain at least 256 bits');
  const usernameToken = crypto.createHmac('sha256', seed)
    .update('divedeep-root-username-v1').digest('base64url').slice(0, 24);
  const passwordToken = crypto.createHmac('sha512', seed)
    .update('divedeep-root-password-v1').digest('base64url').slice(0, 48);
  return {
    username: `fid_${usernameToken}`,
    password: `Fid!7${passwordToken}`,
  };
}

function generateBootstrapAdmin() {
  const seed = crypto.randomBytes(32);
  try {
    return deriveBootstrapAdmin(seed);
  } finally {
    seed.fill(0);
  }
}

function createInstallRouter(appState) {
  const router = express.Router();
  const connectionProofKey = crypto.randomBytes(32);

  router.use((req, res, next) => {
    req.sentinelOmitBodies = true;
    const scrubRequest = () => {
      if (!req.body || typeof req.body !== 'object') return;
      for (const field of ['password', 'connectionProof']) {
        if (Object.prototype.hasOwnProperty.call(req.body, field)) req.body[field] = '';
      }
    };
    res.once('finish', scrubRequest);
    res.once('close', scrubRequest);
    res.setHeader('Cache-Control', 'no-store, max-age=0');
    res.setHeader('Pragma', 'no-cache');
    res.setHeader('Referrer-Policy', 'no-referrer');
    next();
  });

  function notFound(res) {
    return res.status(404).send('Not found');
  }

  function alreadyInstalledResponse(res) {
    return res.status(404).json({ error: 'Not found' });
  }

  router.get('/status', async (req, res) => {
    if (appState.installed && !allowReinstall()) {
      return res.status(404).json({ error: 'Not found' });
    }
    res.json({
      installed: appState.installed,
      configured: appState.configured,
      allowReinstall: allowReinstall(),
    });
  });

  router.post('/test-db', installLimiter, async (req, res) => {
    if (appState.installed && !allowReinstall()) {
      return alreadyInstalledResponse(res);
    }
    const { host, port, user, password, database, createDatabase } = req.body || {};
    if (!user || !database) {
      return res.status(400).json({ error: 'user and database are required' });
    }
    try {
      await testConnection({
        host,
        port,
        user,
        password,
        database,
        createDatabase: Boolean(createDatabase),
      });
      res.setHeader('Clear-Site-Data', '"cache", "storage"');
      res.json({
        ok: true,
        message: 'Connection successful and verified for setup',
        connectionProof: createConnectionProof(req.body || {}, connectionProofKey),
      });
    } catch (err) {
      res.status(400).json({ ok: false, error: err.message });
    }
  });

  router.post('/complete', installLimiter, async (req, res) => {
    if (appState.installed && !allowReinstall()) {
      return alreadyInstalledResponse(res);
    }

    const {
      host = '127.0.0.1',
      port = 3306,
      user,
      password = '',
      database,
      createDatabase = true,
      connectionProof,
      createFirstApiKey = true,
      firstKeyName = 'Default Dialer Key',
      appPort,
      instanceIdentity = {},
      publicOrigin,
      apiOrigin,
      privateStorageDir,
    } = req.body || {};

    if (!user || !database) {
      return res.status(400).json({ error: 'Database user and name are required' });
    }
    if (!verifyConnectionProof(connectionProof, req.body || {}, connectionProofKey)) {
      return res.status(400).json({ error: 'Test this exact database connection again before installing' });
    }

    let configuredPublicOrigin;
    let configuredApiOrigin;
    let configuredPrivateStorageDir;
    try {
      configuredPublicOrigin = normalizeWebOrigin(publicOrigin, 'Customer website URL');
      configuredApiOrigin = normalizeWebOrigin(apiOrigin || requestOrigin(req), 'API URL');
      configuredPrivateStorageDir = preparePrivateStorageDir(privateStorageDir);
    } catch (error) {
      return res.status(400).json({ error: error.message });
    }

    const bootstrapAdmin = generateBootstrapAdmin();
    try { validPassword(bootstrapAdmin.password); }
    catch (error) { return res.status(500).json({ error: 'Secure owner generation failed' }); }

    let identity;
    try {
      identity = generateInstanceIdentity(instanceIdentity && typeof instanceIdentity === 'object'
        ? instanceIdentity
        : {});
    } catch (error) {
      return res.status(400).json({ error: error.message });
    }

    let tempConn;
    try {
      tempConn = await mysql.createConnection({
        host,
        port: Number(port),
        user,
        password,
        multipleStatements: true,
      });
      const safeDb = String(database).replace(/`/g, '');
      if (createDatabase) {
        await tempConn.query(
          `CREATE DATABASE IF NOT EXISTS \`${safeDb}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci`
        );
      }
      await tempConn.query(`USE \`${safeDb}\``);
      await tempConn.end();
      tempConn = null;

      const sessionSecret = crypto.randomBytes(48).toString('hex');
      const secretBoxKey = crypto.randomBytes(48).toString('hex');
      const forensicKey = crypto.randomBytes(48).toString('hex');
      const adminBasePath = generateAdminBasePath();

      writeEnvFile({
        PORT: appPort || process.env.PORT || 3000,
        NODE_ENV: configuredApiOrigin.startsWith('https:') ? 'production' : 'development',
        DB_HOST: host,
        DB_PORT: Number(port),
        DB_USER: user,
        DB_PASSWORD: password,
        DB_NAME: database,
        SESSION_SECRET: sessionSecret,
        SECRET_BOX_KEY: secretBoxKey,
        FORENSIC_KEY: forensicKey,
        ADMIN_BASE_PATH: adminBasePath,
        ALLOW_REINSTALL: 'false',
        COOKIE_SECURE: configuredApiOrigin.startsWith('https:') ? 'true' : 'false',
        TRUST_PROXY: '1',
        CORS_ORIGINS: configuredPublicOrigin,
        DIVEDEEP_PUBLIC_ORIGIN: configuredPublicOrigin,
        DIVEDEEP_API_ORIGIN: configuredApiOrigin,
        DIVEDEEP_PRIVATE_STORAGE_DIR: configuredPrivateStorageDir,
        DIVEDEEP_META_REDIRECT_URI: `${configuredApiOrigin}/divedeep/connect/facebook/callback`,
        ...identityEnv(identity),
      });

      await closePool();
      const pool = createPool({
        host,
        port: Number(port),
        user,
        password,
        database,
      });
      setPool(pool);

      await applySchema(pool);
      const createdAdmin = await createAdmin(
        {
          username: bootstrapAdmin.username,
          password: bootstrapAdmin.password,
          email: null,
          role: 'admin',
        },
        pool
      );

      const verifiedAdmin = await verifyPassword(bootstrapAdmin.username, bootstrapAdmin.password, pool);
      if (!verifiedAdmin || verifiedAdmin.id !== createdAdmin.id || verifiedAdmin.principalType !== 'root') {
        throw new Error('Root owner verification failed');
      }

      let firstKey = null;
      if (createFirstApiKey) {
        firstKey = await createKey({ name: firstKeyName, createdBy: null }, pool);
      }

      await markInstalled(pool);

      appState.installed = true;
      appState.configured = true;
      appState.sessionSecret = sessionSecret;
      appState.adminBasePath = adminBasePath;

      if (typeof appState.onInstalled === 'function') {
        await appState.onInstalled();
      }

      res.setHeader('Clear-Site-Data', '"cache", "storage"');
      res.json({
        ok: true,
        message: 'Installation complete',
        adminBasePath,
        adminLoginUrl: `${adminBasePath}/login`,
        redirect: `${adminBasePath}/login`,
        warning:
          'Save the one-time launch receipt now. The installer is locked and will not reveal it again.',
        checks: {
          databaseConnection: true,
          schemaCreated: true,
          rootOwnerCreated: true,
          rootOwnerLoginVerified: true,
          installerLocked: true,
          bootstrapSeedPersisted: false,
        },
        admin: {
          username: bootstrapAdmin.username,
          password: bootstrapAdmin.password,
          warning: 'One-time credentials. Save them directly into a password manager before leaving this page.',
        },
        launch: {
          now: 'Open the private admin login URL and sign in with the one-time owner credentials.',
          later: 'From the application directory run: npm start',
          healthPath: identity.healthPath,
        },
        frontend: {
          publicOrigin: configuredPublicOrigin,
          apiOrigin: configuredApiOrigin,
          runtimeFileName: 'divedeep-runtime.js',
          runtimeConfig: frontendRuntimeConfig(configuredApiOrigin),
          warning: 'Upload the downloaded runtime file to the customer website root. It contains the API URL only, never credentials.',
        },
        instance: {
          instanceId: identity.instanceId,
          publicApiBasePath: identity.publicApiBasePath,
          webhookBasePath: identity.webhookBasePath,
          healthPath: identity.healthPath,
          apiKeyPrefix: identity.apiKeyPrefix,
          automationNamespace: identity.automationNamespace,
          apiDisplayName: identity.apiDisplayName,
        },
        apiKey: firstKey
          ? {
              id: firstKey.id,
              name: firstKey.name,
              key_prefix: firstKey.key_prefix,
              secret: firstKey.secret,
              warning: 'Copy this API key now. It will not be shown again.',
            }
          : null,
      });
    } catch (err) {
      console.error('Install failed:', err.code || err.name || 'INSTALL_ERROR');
      if (tempConn) {
        try {
          await tempConn.end();
        } catch {
          /* ignore */
        }
      }
      res.status(500).json({ error: err.message || 'Installation failed' });
    }
  });

  router.get('/', async (req, res) => {
    if (appState.installed && !allowReinstall()) {
      return notFound(res);
    }
    res.sendFile(path.join(ROOT, 'public', 'install', 'index.html'));
  });

  return router;
}

module.exports = {
  createInstallRouter,
  canonicalDatabaseInput,
  createConnectionProof,
  verifyConnectionProof,
  deriveBootstrapAdmin,
  generateBootstrapAdmin,
  frontendRuntimeConfig,
  preparePrivateStorageDir,
};
